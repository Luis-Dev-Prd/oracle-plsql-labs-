CREATE TABLE POLIZAS_VINCULOS_LAB (
    POLICY_ID        NUMBER NOT NULL,
    MASTER_POLICY_ID NUMBER NOT NULL,

    CONSTRAINT PK_POLIZAS_VINCULOS_LAB
        PRIMARY KEY (POLICY_ID),

    CONSTRAINT FK_POLIZAS_VINCULOS_LAB
        FOREIGN KEY (POLICY_ID)
        REFERENCES POLIZAS_LAB (POLICY_ID)
);
