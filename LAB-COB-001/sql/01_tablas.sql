-- Ejecutar una sola vez en un esquema de Oracle limpio.

CREATE TABLE CORE_EMISION_LAB (
    OFICINA_ID       VARCHAR2(10) NOT NULL,
    DOC_ID           NUMBER(17)   NOT NULL,
    POLIZA_ID        NUMBER(20)   NOT NULL,
    OBLIGACION_ID    VARCHAR2(20) NOT NULL,
    TIPO_DOCUMENTO   VARCHAR2(15) NOT NULL,
    IMPORTE          NUMBER(18,2) NOT NULL,
    CONSTRAINT PK_CORE_EMISION_LAB
        PRIMARY KEY (OFICINA_ID, DOC_ID),
    CONSTRAINT CK_CORE_EMISION_TIPO
        CHECK (TIPO_DOCUMENTO IN ('PRIMA', 'IMPUESTO')),
    CONSTRAINT CK_CORE_EMISION_IMPORTE
        CHECK (IMPORTE > 0)
);

CREATE TABLE RECIBOS_LAB (
    OFICINA_ID       VARCHAR2(10) NOT NULL,
    RECIBO_ID        NUMBER(20)   NOT NULL,
    OBLIGACION_ID    VARCHAR2(20) NOT NULL,
    POLIZA_ID        NUMBER(20)   NOT NULL,
    IMPORTE_TOTAL    NUMBER(18,2) NOT NULL,
    PARCIALIDAD      VARCHAR2(10) NOT NULL,
    ESTADO           VARCHAR2(15) NOT NULL,
    CONSTRAINT PK_RECIBOS_LAB
        PRIMARY KEY (OFICINA_ID, RECIBO_ID),
    CONSTRAINT UQ_RECIBOS_OBLIGACION
        UNIQUE (OFICINA_ID, OBLIGACION_ID),
    CONSTRAINT CK_RECIBOS_IMPORTE
        CHECK (IMPORTE_TOTAL > 0)
);

CREATE TABLE RECIBO_DETALLE_LAB (
    OFICINA_ID       VARCHAR2(10) NOT NULL,
    RECIBO_ID        NUMBER(20)   NOT NULL,
    DOC_ID           NUMBER(17)   NOT NULL,
    IMPORTE          NUMBER(18,2) NOT NULL,
    CONSTRAINT PK_RECIBO_DETALLE_LAB
        PRIMARY KEY (OFICINA_ID, RECIBO_ID, DOC_ID),
    CONSTRAINT FK_DETALLE_RECIBO
        FOREIGN KEY (OFICINA_ID, RECIBO_ID)
        REFERENCES RECIBOS_LAB (OFICINA_ID, RECIBO_ID),
    CONSTRAINT FK_DETALLE_DOCUMENTO
        FOREIGN KEY (OFICINA_ID, DOC_ID)
        REFERENCES CORE_EMISION_LAB (OFICINA_ID, DOC_ID),
    CONSTRAINT UQ_DETALLE_DOCUMENTO
        UNIQUE (OFICINA_ID, DOC_ID),
    CONSTRAINT CK_DETALLE_IMPORTE
        CHECK (IMPORTE > 0)
);
