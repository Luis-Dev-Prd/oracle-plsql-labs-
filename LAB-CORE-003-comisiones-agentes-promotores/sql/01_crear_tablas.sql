-- LAB-CORE-003: crear en un esquema de laboratorio.
-- Requiere POLIZAS_LAB(POLICY_ID), existente en LAB-CORE-001.

CREATE TABLE AGENTES_LAB (
    AGENT_ID    NUMBER PRIMARY KEY,
    AGENT_NAME  VARCHAR2(80),
    MAIN_AGENT  NUMBER
);

CREATE TABLE COMISIONES_LAB (
    COMMISSION_ID    NUMBER PRIMARY KEY,
    POLICY_ID        NUMBER NOT NULL,
    ANNEX_ID         NUMBER NOT NULL,
    AGENT_ID         NUMBER NOT NULL,
    COMMISSION_TYPE  VARCHAR2(20) NOT NULL,
    COMM_AMOUNT      NUMBER(14,2) NOT NULL,

    CONSTRAINT FK_COM_POL_LAB
        FOREIGN KEY (POLICY_ID)
        REFERENCES POLIZAS_LAB(POLICY_ID),

    CONSTRAINT FK_COM_AG_LAB
        FOREIGN KEY (AGENT_ID)
        REFERENCES AGENTES_LAB(AGENT_ID)
);
